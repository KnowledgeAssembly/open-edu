// Generates dist/widget-catalog-data.js (self-contained ESM module) + its .d.ts
// from dist/widget-catalog-data.json so the catalog data is loadable in any
// JS environment (browser, Vitest, and raw Node ESM) without import attributes.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const jsonPath = join(root, 'dist', 'widget-catalog-data.json');
const jsPath = join(root, 'dist', 'widget-catalog-data.js');
const dtsPath = join(root, 'dist', 'widget-catalog-data.d.ts');

const data = JSON.parse(readFileSync(jsonPath, 'utf-8'));

writeFileSync(
  jsPath,
  '// Auto-generated by scripts/generate-catalog-data-module.mjs. Do not edit.\n' +
    `export default ${JSON.stringify(data)};\n`,
);

writeFileSync(
  dtsPath,
  'declare const data: import("./widget-catalog.js").WidgetCatalogEntry[];\nexport default data;\n',
);

console.log('[core:build] wrote dist/widget-catalog-data.js', jsPath);
